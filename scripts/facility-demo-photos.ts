type PrismaLike = {
  facility: { findUnique: (args: { where: { id: string }; select: { id: true } }) => Promise<{ id: string } | null> };
  facilityMedia: {
    upsert: (args: {
      where: { id: string };
      update: Record<string, unknown>;
      create: Record<string, unknown>;
    }) => Promise<unknown>;
  };
};

export async function seedFacilityDemoPhotos(
  prisma: PrismaLike,
  facilityIds?: string[],
): Promise<number> {
  const ids = facilityIds ?? Object.keys(FACILITY_DEMO_PHOTOS);
  let seeded = 0;

  for (const facilityId of ids) {
    const urls = FACILITY_DEMO_PHOTOS[facilityId];
    if (!urls?.length) continue;

    const facility = await prisma.facility.findUnique({
      where: { id: facilityId },
      select: { id: true },
    });
    if (!facility) continue;

    for (let i = 0; i < urls.length; i++) {
      const url = urls[i];
      const id = `fmedia-${facilityId}-${i}`;
      const key = `demo/facilities/${facilityId}/photo-${i}.jpg`;
      const thumb = url.replace("w=1200&h=800", "w=400&h=300");

      await prisma.facilityMedia.upsert({
        where: { id },
        update: {
          url,
          thumbnailUrl: thumb,
          key,
          mimeType: "image/jpeg",
          width: 1200,
          height: 800,
          displayOrder: i,
        },
        create: {
          id,
          facilityId,
          type: "image",
          key,
          url,
          thumbnailUrl: thumb,
          mimeType: "image/jpeg",
          width: 1200,
          height: 800,
          displayOrder: i,
        },
      });
      seeded += 1;
    }
  }

  return seeded;
}
